"""Generate src/tokenizer/unicode_tables.rs: the Unicode `\\p{L}` (Letter) ranges.

The GPT-2 pre-tokenizer regex needs `\\p{L}`. Rust's `char::is_alphabetic` is the
*Alphabetic* property, which also includes combining marks (Mn/Mc) and letter
numbers (Nl), so it would split Hindi or accented text differently from the
reference. Standard library only:

    python scripts/gen_unicode_tables.py
"""

import pathlib
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "tokenizer" / "unicode_tables.rs"


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        hit = pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main() -> None:
    letters = ranges(lambda cp: unicodedata.category(chr(cp)).startswith("L"))
    lines = [
        "// @generated by scripts/gen_unicode_tables.py -- do not edit by hand.",
        f"// Unicode {unicodedata.unidata_version}, general category L (Lu|Ll|Lt|Lm|Lo).",
        "",
        "/// Sorted, non-overlapping inclusive code point ranges of `\\p{L}`.",
        "#[rustfmt::skip]",
        "pub(super) static LETTER: &[(u32, u32)] = &[",
    ]
    row = []
    for lo, hi in letters:
        row.append(f"(0x{lo:05X}, 0x{hi:05X}),")
        if len(row) == 4:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(letters)} ranges -> {OUT.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
